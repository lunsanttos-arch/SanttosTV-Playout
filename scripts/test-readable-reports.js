"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const ExcelJS = require("exceljs");
const reports = require("../src/core/reporting/playout-report");

(async () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "santtos-readable-report-"));
    try {
        reports.initializePlayoutReports({ userDataPath: root, documentsPath: root });
        const entry = reports.startPlayoutEntry({ id: "media-1", name: "Filme <teste>", path: "C:\\Filme.mp4", duration: 60 });
        const attemptedAt = Date.now();
        await new Promise(resolve => setTimeout(resolve, 30));
        reports.markPlayoutEntryReady(entry.id);
        const firstReadyAt = Date.now();
        await new Promise(resolve => setTimeout(resolve, 30));
        reports.markPlayoutEntryReady(entry.id); // Resume cannot change original entry time.
        reports.finishPlayoutEntry(entry.id, "EXECUTADO", 15);
        const persisted = JSON.parse(fs.readFileSync(path.join(root, "reporting", "playout-report-state.json"), "utf8")).entries[0];
        assert(Date.parse(persisted.startedAt) >= attemptedAt + 20);
        assert(Date.parse(persisted.startedAt) <= firstReadyAt);
        assert(Date.parse(persisted.attemptedAt) < Date.parse(persisted.startedAt));
        const files = await reports.listReportFiles();
        assert.equal(files.length, 1);
        const htmlPath = path.join(reports.getReportFolder(), files[0].name);
        const html = fs.readFileSync(htmlPath, "utf8");
        assert(html.includes("<table>") && html.includes("EXECUTADO"));
        assert(html.includes("&lt;teste&gt;"), "Names must remain escaped in readable reports");
        const workbook = new ExcelJS.Workbook(); await workbook.xlsx.readFile(htmlPath.replace(/\.html$/, ".xlsx"));
        assert.equal(workbook.worksheets[0].rowCount, 2);
        assert.equal(workbook.worksheets[0].getRow(2).getCell(8).value, "EXECUTADO");
        assert.equal(workbook.worksheets[0].getRow(2).getCell(9).value, "C:\\Filme.mp4");
        assert(fs.existsSync(htmlPath.replace(/\.html$/, ".xml")));
        const failed = reports.startPlayoutEntry({ id: "bad", name: "Vídeo indisponível", path: "C:\\bad.mp4", duration: 30 });
        reports.finishPlayoutEntry(failed.id, "PULADO_POR_ERRO", 0, { reason: "Arquivo removido <erro>", contingency: "Tela preta" });
        reports.updatePlayoutEntrySuccessor(failed.id, "Vídeo seguinte");
        await reports.listReportFiles();
        const updated = fs.readFileSync(htmlPath, "utf8");
        assert(updated.includes("PULADO POR ERRO") && updated.includes("Arquivo removido &lt;erro&gt;") && updated.includes("Vídeo seguinte"));
        await workbook.xlsx.readFile(htmlPath.replace(/\.html$/, ".xlsx"));
        assert.equal(workbook.worksheets[0].getRow(3).getCell(10).value, "Arquivo removido <erro>");
        assert.equal(workbook.worksheets[0].getRow(3).getCell(11).value, "Vídeo seguinte");
        const xml = fs.readFileSync(htmlPath.replace(/\.html$/, ".xml"), "utf8");
        assert(xml.includes("PULADO_POR_ERRO") && xml.includes("<conteudo_seguinte>Vídeo seguinte</conteudo_seguinte>"));
        reports.startPlayoutEntry({ id: "crash", name: "Interrompido", path: "C:\\crash.mp4", duration: 30 });
        reports.initializePlayoutReports({ userDataPath: root, documentsPath: root });
        await reports.listReportFiles();
        assert(fs.readFileSync(htmlPath, "utf8").includes("Não recuperado"));
        assert(fs.readFileSync(htmlPath.replace(/\.html$/, ".xml"), "utf8").includes("<duracao_exibida_conhecida>false</duracao_exibida_conhecida>"));
        const unavailable = path.join(root, "not-a-folder");
        fs.writeFileSync(unavailable, "file");
        fs.writeFileSync(path.join(root, "reporting", "playout-report-config.json"), JSON.stringify({ reportFolder: unavailable }));
        reports.initializePlayoutReports({ userDataPath: root, documentsPath: root });
        assert.equal(reports.getReportFolder(), path.dirname(htmlPath));
        await reports.listReportFiles();
        console.log("REPORT QA: APROVADO — HTML legível, XLSX válido e compatibilidade XML.");
    } finally { fs.rmSync(root, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
